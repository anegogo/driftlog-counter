// iOS only opens the share sheet if share() runs straight from the tap, so the image file is made ahead of time.
// Returns the object to pass to share(); its file appears once the PNG is encoded.
function prepareShare(canvas, { fileName, text, url }){
  const s = { text, url, file: null };
  canvas.toBlob(b => { if (b) s.file = new File([b], fileName, { type: 'image/png' }); }, 'image/png');
  return s;
}
const canShare = () => typeof navigator !== 'undefined' && !!navigator.share;
// The status line is often scrolled out of view by the time a button is pressed, so the button says what happened.
async function copy(s, { button, setStatus }){
  const label = button.textContent;
  try {
    await navigator.clipboard.writeText(s.url ? `${s.text} ${s.url}` : s.text);
    setStatus('Copied a line and the link. Paste it anywhere.');
    button.textContent = 'Copied';
    setTimeout(() => { if (button.textContent === 'Copied') button.textContent = label; }, 2000);
  } catch (e){
    setStatus(`Link: ${s.url || SITE + '/'}`);
    window.prompt('Copy this link:', s.url || SITE + '/');
  }
}
// Share sheet with the image and the link when the browser has one, otherwise copy the link.
async function share(s, opts){
  if (!s) return;
  if (!canShare()) return copy(s, opts);
  try {
    if (s.file && navigator.canShare && navigator.canShare({ files: [s.file] })) await navigator.share({ files: [s.file], text: s.url ? `${s.text} ${s.url}` : s.text });
    else await navigator.share(s.url ? { text: s.text, url: s.url } : { text: s.text });
  } catch (e){
    if (e && e.name === 'AbortError') return;
    return copy(s, opts);
  }
}
