// ---------- the border file ----------
// countries50.json: [{ n: name, a: ISO code, k: 1 if one of the 194, t: 'Polygon' | 'MultiPolygon', c: rings
// delta-encoded at 1/10000 degree, b: bounding box }], smallest first so an enclave wins a point lookup.
// Decoded: { n, a, k, b, polys: [[Float64Array lon,lat,...]], pb: bounding box of each polygon's outer ring }.
function decodeRing(arr){
  const out = new Float64Array(arr.length);
  let x = 0, y = 0;
  for (let i = 0; i < arr.length; i += 2){ x += arr[i]; y += arr[i+1]; out[i] = x / 10000; out[i+1] = y / 10000; }
  return out;
}
function ringBox(r){
  let a = Infinity, b = Infinity, c = -Infinity, d = -Infinity;
  for (let i = 0; i < r.length; i += 2){ const x = r[i], y = r[i+1]; if (x < a) a = x; if (x > c) c = x; if (y < b) b = y; if (y > d) d = y; }
  return [a, b, c, d];
}
