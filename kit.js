// ---------- result links: /c/<N>/#v=1.<mask>[&y=<years>] ----------
// The mask is one bit per country in table order, six bits per base64url character, most significant first,
// with trailing zero characters dropped: 33 characters at most. Only the number is in the path, which the
// server sees; the list is after the #, which browsers never send.
const B64 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_';
const MASK_LEN = Math.ceil(COUNTRIES.length / 6);
const MAX_FRAGMENT = 512;          // longer than any link this version writes (33 + 194 + a few); anything longer is not ours
const YEAR_BASE = 1975;            // optional years: one character per country in link order, 1976–2038, 'A' = unknown
function encodeMask(codes){
  const v = new Array(MASK_LEN).fill(0);
  for (const code of codes){ const c = BY_CODE.get(code); if (c) v[(c.i / 6) | 0] |= 32 >> (c.i % 6); }
  return v.map(x => B64[x]).join('').replace(/A+$/, '');
}
// Set of codes in table order, or null if the string is not a version 1 mask.
function decodeMask(s){
  if (typeof s !== 'string' || s.length > MASK_LEN || !/^[A-Za-z0-9_-]*$/.test(s)) return null;
  const codes = new Set();
  for (let k = 0; k < s.length; k++){
    const x = B64.indexOf(s[k]);
    for (let b = 0; b < 6; b++){
      if (!(x & (32 >> b))) continue;
      const i = k * 6 + b;
      if (i >= COUNTRIES.length) return null;     // bits past the last country: not something we wrote
      codes.add(COUNTRIES[i].code);
    }
  }
  return codes;
}
function encodeYears(codes, years){
  let s = '', any = false;
  for (const c of COUNTRIES){
    if (!codes.has(c.code)) continue;
    const y = years.get(c.code), v = y > YEAR_BASE && y - YEAR_BASE < 64 ? y - YEAR_BASE : 0;
    if (v) any = true;
    s += B64[v];
  }
  return any ? s : '';
}
function decodeYears(s, codes){
  if (s.length !== codes.size || !/^[A-Za-z0-9_-]*$/.test(s)) return null;
  const years = new Map();
  let k = 0;
  for (const code of codes){ const v = B64.indexOf(s[k++]); if (v) years.set(code, YEAR_BASE + v); }
  return years;
}
// The part after the #. Years are left out unless given: the share buttons do not send them.
function linkHash(codes, years){
  const set = new Set(codes), y = years ? encodeYears(set, years) : '';
  return 'v=1.' + encodeMask(set) + (y ? '&y=' + y : '');
}
const resultUrl = (codes, years) => `${SITE}/c/${countOf(new Set(codes))}/#${linkHash(codes, years)}`;
// Reads location.hash. null: not a result link at all (no hash, #app...). { error }: a result link that cannot
// be used ('too-long', 'broken', 'version'). Otherwise { codes: Set, years: Map | null }. Years that do not fit
// are dropped and the countries kept; unknown keys are ignored, so version 1 can grow new optional parts.
function readLink(hash){
  let h = String(hash || '').replace(/^#/, '');
  // Some mail link-wrappers hand the link back as #v%3D1.… ; nothing we write needs a % itself.
  if (/%[0-9A-Fa-f]{2}/.test(h) && h.length <= MAX_FRAGMENT * 3){ try { h = decodeURIComponent(h); } catch (e){} }
  if (!/(^|&)v=/.test(h)) return null;
  if (h.length > MAX_FRAGMENT) return { error: 'too-long' };
  const p = new Map();
  for (const part of h.split('&')){ const eq = part.indexOf('='); if (eq > 0 && !p.has(part.slice(0, eq))) p.set(part.slice(0, eq), part.slice(eq + 1)); }
  const m = /^(\d{1,4})\.(.*)$/.exec(p.get('v') || '');
  if (!m) return { error: 'broken' };
  if (m[1] !== '1') return { error: 'version' };
  const codes = decodeMask(m[2]);
  if (!codes) return { error: 'broken' };
  return { codes, years: p.has('y') ? decodeYears(p.get('y'), codes) : null };
}

