// hits: Map featureIndex -> Set of polygon indexes that were hit, or null when only the country is known.
// Returns layerOf(fi) for drawWorld. France's outline includes French Guiana, Réunion and the Antilles: a trip
// to Paris should not paint South America, so only parts within 1,500 km of a hit (or of the mainland) are painted.
function layers(FEATS, hits, colorOf){
  return fi => {
    if (!hits.has(fi)) return null;
    const f = FEATS[fi], h = hits.get(fi), color = colorOf ? colorOf(fi) : COLORS.mine;
    if (f.a !== 'FR') return { color, on: () => true };
    let anchor = h && h.size ? [...h] : null;
    if (!anchor){ let best = 0; f.pb.forEach((b, pi) => { if ((b[2] - b[0]) * (b[3] - b[1]) > (f.pb[best][2] - f.pb[best][0]) * (f.pb[best][3] - f.pb[best][1])) best = pi; }); anchor = [best]; }
    const hc = anchor.map(pi => center(f.pb[pi]));
    return { color, on: pi => (h && h.has(pi)) || hc.some(p => km(p, center(f.pb[pi])) < 1500) };
  };
}
// box: { x, y, w, h } of the map on the canvas. layerOf(fi) -> null (plain land) or { color: [fill, stroke], on(pi) }.
// Places too small to see get a dot in their colour. opts.paintedOnly skips the plain land, for drawing frames over
// a base map drawn once (drawWorld(c, FEATS, box, null) into an offscreen canvas), as the video will.
function drawWorld(c, FEATS, box, layerOf, opts = {}){
  const s = box.w / 1200, dots = [];
  const project = (lon, lat) => [box.x + (lon + 180) / 360 * box.w, box.y + (85 - lat) / 145 * box.h];
  const shape = (f, keep) => {
    c.beginPath();
    f.polys.forEach((poly, pi) => {
      if (!keep(pi)) return;
      for (const r of poly){
        for (let i = 0; i < r.length; i += 2){
          const [x, y] = project(r[i], Math.max(r[i+1], -60));
          (i === 0 || Math.abs(r[i] - r[i-2]) > 180) ? c.moveTo(x, y) : c.lineTo(x, y);
        }
        c.closePath();
      }
    });
  };
  const paint = ([fill, stroke], width) => { c.fillStyle = fill; c.fill('evenodd'); c.strokeStyle = stroke; c.lineWidth = width; c.stroke(); };
  FEATS.forEach((f, fi) => {
    if (f.b[3] < -60) return;
    const L = layerOf ? layerOf(fi) : null;
    if (!opts.paintedOnly){ shape(f, L ? pi => !L.on(pi) : () => true); paint(COLORS.land, 0.6 * s); }
    if (!L) return;
    shape(f, L.on);
    paint(L.color, 1.2 * s);
    const [x0, y0] = project(f.b[0], f.b[3]), [x1, y1] = project(f.b[2], f.b[1]);
    if ((x1 - x0) < 7 * s && (y1 - y0) < 7 * s) dots.push([(x0 + x1) / 2, (y0 + y1) / 2, L.color[0]]);
  });
  for (const [x, y, col] of dots){
    c.beginPath(); c.arc(x, y, 7 * s, 0, Math.PI * 2);
    c.fillStyle = rgba(col, '.25'); c.fill();
    c.beginPath(); c.arc(x, y, 3.2 * s, 0, Math.PI * 2);
    c.fillStyle = col; c.fill();
  }
}

