#!/usr/bin/env python3
"""Prints the country table for kit.js (the block between `// @table-start` and `// @table-end`),
or with --write, replaces that block in the given kit.js.

The 194 counted countries (193 UN member states plus Taiwan) come from countries50.json (k=1),
sorted by ISO 3166-1 alpha-2. That order is link version 1: never reorder it, never insert into it.

Regions are for browsing the picker only (search is the main way in). They follow the usual
seven continents, with the Americas split into North (incl. Central America and the Caribbean)
and South. Countries people commonly place on either side are listed in both.

  python3 build_kit_table.py <site>/countries50.json            # print
  python3 build_kit_table.py <site>/countries50.json --write <site>/kit.js
"""
import json, sys, re

F, A, E, N, S, O = 'F', 'A', 'E', 'N', 'S', 'O'   # Africa, Asia, Europe, North America, South America, Oceania
REGION = {}
def put(r, codes):
    for c in codes.split():
        REGION[c] = REGION.get(c, '') + r

put(F, 'DZ AO BJ BW BF BI CV CM CF TD KM CG CD CI DJ EG GQ ER SZ ET GA GM GH GN GW KE LS LR LY MG MW ML MR MU MA '
       'MZ NA NE NG RW ST SN SC SL SO ZA SS SD TZ TG TN UG ZM ZW')
put(E, 'AL AD AT BY BE BA BG HR CY CZ DK EE FI FR DE GR HU IS IE IT LV LI LT LU MT MD MC ME NL MK NO PL PT RO RU '
       'SM RS SK SI ES SE CH TR UA GB')
put(A, 'AF AM AZ BH BD BT BN KH CN GE IN ID IR IQ IL JP JO KZ KW KG LA LB MY MV MN MM NP KP OM PK PH QA SA SG KR '
       'LK SY TJ TH TL TM AE UZ VN YE TW')
put(A, 'RU TR CY')          # also in Asia
put(E, 'GE AM AZ KZ')       # also in Europe
put(N, 'AG BS BB BZ CA CR CU DM DO SV GD GT HT HN JM MX NI PA KN LC VC TT US')
put(S, 'AR BO BR CL CO EC GY PY PE SR UY VE')
put(O, 'AU FJ KI MH FM NR NZ PW PG WS SB TO TV VU')


def build(countries_path):
    feats = json.load(open(countries_path))
    names = {}
    for f in feats:
        if f.get('k'):
            names.setdefault(f['a'], f['n'])
    codes = sorted(names)
    assert len(codes) == 194, len(codes)
    missing = [c for c in codes if c not in REGION]
    extra = [c for c in REGION if c not in names]
    assert not missing and not extra, (missing, extra)
    other = sorted({f['n'] for f in feats if not f.get('k') and f.get('a')})
    lines = ['// @table-start (generated by counter-tools/build_kit_table.py from countries50.json)',
             'const TABLE = `']
    lines += [f'{c} {REGION[c]} {names[c]}' for c in codes]
    lines += ['`;', f"const OTHER_PLACES = {json.dumps('|'.join(other), ensure_ascii=False)}.split('|');",
              '// @table-end']
    counts = {r: sum(1 for c in codes if r in REGION[c]) for r in 'FAENSO'}
    return '\n'.join(lines), counts


if __name__ == '__main__':
    block, counts = build(sys.argv[1])
    if '--write' in sys.argv:
        path = sys.argv[sys.argv.index('--write') + 1]
        src = open(path, encoding='utf-8').read()
        new = re.sub(r'// @table-start.*?// @table-end', lambda m: block, src, count=1, flags=re.S)
        assert new != src or block in src, 'no @table-start/@table-end block in ' + path
        open(path, 'w', encoding='utf-8').write(new)
        print('wrote', path, counts, file=sys.stderr)
    else:
        print(block)
        print(counts, file=sys.stderr)
